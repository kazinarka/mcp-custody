"""Generate L0 policies for a suite from its user tasks only. Injection tasks are never read,
so a policy cannot be tuned to the attacks it is scored against.

- tools: least privilege. Only tools some user task needs are allowed.
- args: tools, plus every sink argument limited to the values user tasks use. This is an
  oracle (an operator who knows every legitimate recipient in advance), so it is an upper
  bound for static allowlists, not a realistic deployment.
"""

import json
from typing import Any
from urllib.parse import urlsplit

from agentdojo.task_suite.task_suite import TaskSuite

LEVELS = ("tools", "args")

# Arguments that choose where an action goes or what it acts on (threat model section 6),
# picked from tool signatures. "hosts" arguments are URLs constrained by host.
SINKS: dict[str, dict[str, dict[str, str]]] = {
    "banking": {
        "send_money": {"recipient": "values"},
        "schedule_transaction": {"recipient": "values"},
        "update_scheduled_transaction": {"id": "values", "recipient": "values"},
        "update_password": {"password": "values"},
    },
    "slack": {
        "send_direct_message": {"recipient": "values"},
        "send_channel_message": {"channel": "values"},
        "add_user_to_channel": {"user": "values", "channel": "values"},
        "invite_user_to_slack": {"user": "values", "user_email": "values"},
        "remove_user_from_slack": {"user": "values"},
        "get_webpage": {"url": "hosts"},
        "post_webpage": {"url": "hosts"},
    },
    "travel": {
        "send_email": {"recipients": "values", "cc": "values", "bcc": "values",
                       "attachments": "values"},
        "reserve_hotel": {"hotel": "values"},
        "reserve_restaurant": {"restaurant": "values"},
        "reserve_car_rental": {"company": "values"},
        "create_calendar_event": {"participants": "values"},
        "cancel_calendar_event": {"event_id": "values"},
    },
    "workspace": {
        "send_email": {"recipients": "values", "cc": "values", "bcc": "values",
                       "attachments": "values"},
        "delete_email": {"email_id": "values"},
        "share_file": {"file_id": "values", "email": "values"},
        "create_calendar_event": {"participants": "values"},
        "add_calendar_event_participants": {"event_id": "values", "participants": "values"},
        "cancel_calendar_event": {"event_id": "values"},
        "reschedule_calendar_event": {"event_id": "values"},
        "delete_file": {"file_id": "values"},
    },
}


def _host(url: str) -> str:
    parts = urlsplit(url if "://" in url else f"https://{url}")
    return (parts.hostname or "").lower()


def generate(suite: TaskSuite, level: str) -> str:
    if level not in LEVELS:
        raise ValueError(f"unknown level {level!r}")
    sinks = SINKS[suite.name]
    tools: set[str] = set()
    values: dict[tuple[str, str], list[Any]] = {}
    for task in suite.user_tasks.values():
        env = task.init_environment(suite.load_and_inject_default_environment({}))
        for call in task.ground_truth(env):
            tools.add(call.function)
            for arg, kind in sinks.get(call.function, {}).items():
                if arg not in call.args or call.args[arg] is None:
                    continue
                raw = call.args[arg]
                items = raw if isinstance(raw, list) else [raw]
                if kind == "hosts":
                    items = [_host(i) for i in items]
                bucket = values.setdefault((call.function, arg), [])
                bucket.extend(i for i in items if i not in bucket)

    lines = [
        f"# Generated by custody-bench for suite {suite.name}, level {level}.",
        "# Source: user task ground truths only.",
        'default = "deny"',
        "",
    ]
    for tool in sorted(tools):
        lines.append(f"[tools.{tool}]")
        if level == "args":
            for arg, kind in sinks.get(tool, {}).items():
                key = "hosts" if kind == "hosts" else "one_of"
                # A sink never used legitimately gets an empty list: any value is refused.
                allowed = values.get((tool, arg), [])
                lines.append(f"args.{arg}.{key} = {_toml(allowed)}")
        lines.append("")
    return "\n".join(lines)


def _toml(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)  # JSON string escapes are valid TOML basic strings
    if isinstance(value, list):
        return "[" + ", ".join(_toml(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} = {_toml(v)}" for k, v in value.items()) + " }"
    raise TypeError(f"cannot write {type(value).__name__} as TOML")
